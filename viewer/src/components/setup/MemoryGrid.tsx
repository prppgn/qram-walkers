// MemoryGrid (D9): the classical memory as a 2^n × m grid of toggles (row = cell with
// address a₁…aₙ, column = data bit b_j), fill presets and a text import.
import { useEffect, useState } from "react";
import {
  allAddresses,
  fillMemory,
  formatMemoryText,
  isMemorySpec,
  MEMORY_FILLS,
  parseMemoryText,
  type MemoryDraft,
  type MemoryFill,
} from "./configModel";

const FILL_TIPS: Record<MemoryFill, string> = {
  zeros: "Every cell stores 0…0",
  ones: "Every cell stores 1…1",
  random: "Random bits, drawn here in the browser (shown explicitly, sent as bits)",
  identity: "Cell a stores the m least significant bits of its own address a",
};

const sub = (i: number) => String(i).replace(/\d/g, (d) => "₀₁₂₃₄₅₆₇₈₉"[Number(d)]!);

export function MemoryGrid(props: {
  n: number;
  m: number;
  memory: MemoryDraft;
  /** Addresses in the input superposition: their cells are highlighted. */
  queried: ReadonlySet<string>;
  onChange: (memory: number[][]) => void;
}) {
  const { n, m, memory, queried, onChange } = props;
  const [importOpen, setImportOpen] = useState(false);
  const [text, setText] = useState("");
  const [parseError, setParseError] = useState<string | null>(null);

  // Any change of the memory (fill, toggle, preset, resize) makes the pasted text stale.
  useEffect(() => {
    setImportOpen(false);
    setParseError(null);
  }, [memory, n, m]);

  const spec = isMemorySpec(memory) ? memory : null;
  /** Bits to display; null while the engine is to generate them (fill rule). */
  const shown: number[][] | null = spec ? null : (memory as number[][]);
  const base = (): number[][] => (shown ? shown.map((r) => [...r]) : fillMemory("zeros", n, m, Math.random));
  const addresses = allAddresses(n);

  const toggle = (cell: number, j: number) => {
    const next = base();
    next[cell]![j] = next[cell]![j] ? 0 : 1;
    onChange(next);
  };

  const openImport = () => {
    setText(shown ? formatMemoryText(shown, n) : "");
    setParseError(null);
    setImportOpen(true);
  };

  const apply = () => {
    const r = parseMemoryText(text, n, m);
    if ("error" in r) {
      setParseError(r.error);
      return;
    }
    setParseError(null);
    setImportOpen(false);
    onChange(r.bits);
  };

  return (
    <div className="memory-grid">
      <div className="setup-row wrap">
        <span className="muted">Fill:</span>
        {MEMORY_FILLS.map((f) => (
          <button
            key={f}
            type="button"
            className="btn"
            title={FILL_TIPS[f]}
            data-testid={`memory-fill-${f}`}
            onClick={() => onChange(fillMemory(f, n, m, Math.random))}
          >
            {f}
          </button>
        ))}
        <button
          type="button"
          className={`btn${importOpen ? " active" : ""}`}
          title="Paste the memory as text: one line per cell in cell order, m bits per line, optionally 'address,bits'"
          data-testid="memory-import"
          onClick={() => (importOpen ? setImportOpen(false) : openImport())}
        >
          Import text…
        </button>
      </div>

      {importOpen && (
        <div className="memory-import">
          <textarea
            rows={Math.min(8, 1 << n)}
            value={text}
            spellCheck={false}
            aria-label="Memory as text"
            title={`One line per cell (${1 << n} lines) in cell order: ${m} bit${m > 1 ? "s" : ""} per line, e.g. ${"0".repeat(m)} or ${"1".repeat(n)},${"0".repeat(m)}`}
            placeholder={addresses
              .slice(0, 2)
              .map((a) => `${a},${"0".repeat(m)}`)
              .join("\n")}
            onChange={(e) => setText(e.target.value)}
          />
          <div className="setup-row">
            <button type="button" className="btn" title="Parse the text and replace the memory" onClick={apply}>
              Apply
            </button>
            <button type="button" className="btn" title="Close the text import without changes" onClick={() => setImportOpen(false)}>
              Cancel
            </button>
          </div>
          {parseError && (
            <div className="setup-error" role="alert" data-testid="memory-parse-error">
              {parseError}
            </div>
          )}
        </div>
      )}

      {spec && (
        <div className="setup-note" data-testid="memory-spec">
          {spec.fill} (seed {spec.seed ?? "none"}), generated by the engine: the values appear after the run. Click
          a cell (starting from zeros) or a fill button to set the memory explicitly instead.
        </div>
      )}

      <div className="memory-scroll">
        <table className="grid memory-table">
          <thead>
            <tr>
              <th title="Cell index l = 1 + Σ aᵢ 2^(n−i)">l</th>
              <th title="Address a₁…aₙ of the cell">
                a₁…a{sub(n)}
              </th>
              {Array.from({ length: m }, (_, j) => (
                <th key={j} title={`Data bit b${sub(j + 1)} stored in each cell (read out by the data walker D${sub(j + 1)})`}>
                  b{sub(j + 1)}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {addresses.map((a, cell) => (
              <tr key={a} className={queried.has(a) ? "queried" : undefined}>
                <td className="muted">{cell + 1}</td>
                <td className="mono" title={queried.has(a) ? `|${a}⟩ is in the input superposition` : undefined}>
                  {a}
                </td>
                {Array.from({ length: m }, (_, j) => {
                  const v = shown?.[cell]?.[j];
                  return (
                    <td key={j}>
                      <button
                        type="button"
                        className={`mem-cell${v ? " on" : ""}${spec ? " pending" : ""}`}
                        data-testid="memory-cell"
                        aria-pressed={v === 1}
                        aria-label={`b${j + 1} of cell ${a} = ${v ?? "unknown"}`}
                        title={`Bit b${sub(j + 1)} of cell |${a}⟩: click to toggle`}
                        onClick={() => toggle(cell, j)}
                      >
                        {v ?? "?"}
                      </button>
                    </td>
                  );
                })}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
